#!/usr/bin/env node
// Builds src/public/assets.generated.ts from public/a/: the public link's runtime, the files the
// Obysphere serves under /a/ (spec/sphere-api.md section 11), as strings the Worker and the Node
// build both import (neither reads files at run time), each script with its SRI hash, and the
// Obysphere's own page with those hashes in its <script integrity>. A client's own page pins the
// same hashes, so the scripts' bytes are part of what the Obysphere serves: change one and its hash
// changes with it.
//
//   node scripts/gen-viewer.mjs           write it
//   node scripts/gen-viewer.mjs --check   fail if it differs from public/a/

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const server = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(server, "public", "a");
const OUT = join(server, "src", "public", "assets.generated.ts");
const read = (name) => readFileSync(join(dir, name), "utf8");
const sri = (text) => `sha384-${createHash("sha384").update(text, "utf8").digest("base64")}`;

const files = {
  "viewer.js": { type: "text/javascript; charset=utf-8", body: read("viewer.js") },
  "vendor/age.bundle.js": { type: "text/javascript; charset=utf-8", body: read("vendor/age.bundle.js") },
  "vendor/LICENSES.txt": { type: "text/plain; charset=utf-8", body: read("vendor/LICENSES.txt") },
};
const SRI = { "viewer.js": sri(files["viewer.js"].body), "vendor/age.bundle.js": sri(files["vendor/age.bundle.js"].body) };
const page = read("viewer.html").replace("{{AGE_SRI}}", SRI["vendor/age.bundle.js"]).replace("{{VIEWER_SRI}}", SRI["viewer.js"]);
if (page.includes("{{")) throw new Error("public/a/viewer.html has a placeholder gen-viewer.mjs doesn't fill");

const out = `// Generated by scripts/gen-viewer.mjs from public/a/: edit those files, then run \`pnpm run gen:viewer\`.
// The public link's runtime (spec/sphere-api.md section 11): what the Obysphere serves under /a/.

/** The files under /a/, by path: their Content-Type and their text. */
export const ASSETS: Record<string, { type: string; body: string }> = ${JSON.stringify(files, null, 2)};

/** Each script's SRI hash (sha384), which a page that loads it pins in its <script integrity>. */
export const SRI: Record<"viewer.js" | "vendor/age.bundle.js", string> = ${JSON.stringify(SRI, null, 2)};

/** The Obysphere's own page for a link whose owner's client uploaded none: it names no product. */
export const PAGE = ${JSON.stringify(page)};
`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== out) {
    console.error("src/public/assets.generated.ts differs from public/a/: run `pnpm run gen:viewer` and commit it.");
    process.exit(1);
  }
  console.log(`src/public/assets.generated.ts matches public/a/ (viewer.js ${SRI["viewer.js"]}, age.bundle.js ${SRI["vendor/age.bundle.js"]}).`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote src/public/assets.generated.ts (${out.length} bytes)`);
}
